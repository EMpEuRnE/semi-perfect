import {PGlite} from '@electric-sql/pglite';
import {readFileSync,readdirSync} from 'node:fs';
import console from 'node:console';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec(`create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb); create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$; grant usage on schema auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;`);
const migrations=readdirSync('supabase/migrations').sort();
for(const f of migrations.filter(f=>f<'202610250008'))await db.exec(readFileSync('supabase/migrations/'+f,'utf8'));
await db.exec(readFileSync('supabase/seed.sql','utf8'));
const uid='10000000-0000-4000-8000-000000000002',admin='10000000-0000-4000-8000-000000000004',mission='40000000-0000-4000-8000-000000000001';
const one=async sql=>(await db.query(sql)).rows[0];
await db.exec(`select set_config('request.jwt.claim.sub','${uid}',false);set role authenticated;`);
const legacy=(await one(`select public.join_mission('${mission}') id`)).id;
const pending=(await one(`select public.submit_mission_activity('${legacy}',1000) id`)).id;
await db.exec('reset role');
const beforeRounds=(await db.query('select to_jsonb(um) value from public.user_missions um order by id')).rows;
const beforeLedger=(await db.query('select to_jsonb(pt) value from public.point_transactions pt order by id')).rows;
const beforeMissions=(await db.query('select to_jsonb(m) value from public.missions m order by id')).rows;
for(const f of migrations.filter(f=>f>='202610250008'))await db.exec(readFileSync('supabase/migrations/'+f,'utf8'));
assert.deepEqual((await db.query("select to_jsonb(um)-'participation_date'-'mission_snapshot' value from public.user_missions um order by id")).rows,beforeRounds);
assert.deepEqual((await db.query("select to_jsonb(pt)-'user_mission_id' value from public.point_transactions pt order by id")).rows,beforeLedger);
assert.deepEqual((await db.query("select to_jsonb(m)-'recurrence'-'difficulty'-'participation_terms'-'allowed_activity_types'-'seed_key' value from public.missions m where seed_key is null order by id")).rows,beforeMissions);
console.log('OK upgrade preserves original participation, ledger and mission fields exactly');
await db.exec(`select set_config('request.jwt.claim.sub','${uid}',false);set role authenticated;`);
assert.equal((await one(`select public.join_mission('${mission}') id`)).id,legacy);
console.log('OK legacy once-only join still returns same participation');
await db.exec(`reset role;select set_config('request.jwt.claim.sub','${admin}',false);set role authenticated;`);
await db.query(`select public.review_activity('${pending}',true)`);
assert.equal(Number((await one(`select progress_value from public.user_missions where id='${legacy}'`)).progress_value),1000);
console.log('OK pre-upgrade pending activity can still be reviewed');
await db.exec(`reset role;select set_config('request.jwt.claim.sub','${uid}',false);set role authenticated;`);
const final=(await one(`select public.submit_mission_activity('${legacy}',4000) id`)).id;
await db.exec(`reset role;select set_config('request.jwt.claim.sub','${admin}',false);set role authenticated;`);
await db.query(`select public.review_activity('${final}',true)`);
assert.equal((await one(`select amount from public.point_transactions where user_mission_id='${legacy}'`)).amount,300);
console.log('OK existing in-progress account completes and receives original once-only reward');
await db.close();
