import assert from 'node:assert/strict';
import console from 'node:console';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
function load(file,imports={}) {
 const exports={};
 const code=ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 runInNewContext(code,{exports,require:key=>{if(!(key in imports))throw new Error('Unexpected import '+key);return imports[key];}});
 return exports;
}
const rounds=load('src/lib/mission-rounds.ts');
let count=0;
const ok=(name,value)=>{assert.ok(value,name);console.log('OK',++count,name);};
ok('UI Bangkok date before midnight',rounds.bangkokDay(new Date('2026-10-25T16:59:59Z'))==='2026-10-25');
ok('UI Bangkok date after midnight',rounds.bangkokDay(new Date('2026-10-25T17:00:00Z'))==='2026-10-26');
ok('valid leap day accepted',rounds.isRoundDay('2028-02-29'));
ok('invalid calendar day rejected',!rounds.isRoundDay('2026-02-29'));
ok('invalid date syntax rejected',!rounds.isRoundDay('25/10/2026'));
ok('pending data is not labeled approved',rounds.roundStatus({status:'joined',pending_value:3000})==='รอตรวจสอบ');
ok('rejection offers resubmission',rounds.roundStatus({status:'in_progress',last_status:'rejected'}).includes('ส่งใหม่'));
ok('completed status explicitly requires approval',rounds.roundStatus({status:'completed'})==='สำเร็จและอนุมัติแล้ว');

const today='2026-10-26',yesterday='2026-10-25';
const baseMission={id:'daily',title:'Current edited title',description:'Daily mission',mission_type:'steps',activity_type:'steps',allowed_activity_types:['steps'],target_value:6000,target_unit:'steps',points:999,requires_evidence:false,status:'active',starts_at:null,ends_at:null,created_at:'2026-10-01',recurrence:'daily',difficulty:'easy',participation_terms:'Current terms'};
const snapshot={...baseMission,title:'Original round title',target_value:3000,points:30,requires_evidence:true,participation_terms:'Original terms'};
const once={...baseMission,id:'once',title:'Existing once-only mission',recurrence:'once',points:25};
const todayRound={id:'today-round',mission_id:'daily',user_id:'self',status:'joined',progress_value:0,participation_date:today,mission_snapshot:snapshot};
const oldRound={...todayRound,id:'old-round',participation_date:yesterday};
const onceRound={...todayRound,id:'once-round',mission_id:'once',participation_date:null,mission_snapshot:null};
let configured=true;
const tables={missions:[baseMission,once],user_missions:[todayRound,oldRound,onceRound],activities:[],point_transactions:[],mission_activity_totals:[{user_mission_id:'today-round',reported_value:'1500',pending_value:'1500',last_status:'pending'},{user_mission_id:'old-round',reported_value:'3000',pending_value:'3000',last_status:'pending'}]};
const db={from(table){
 let rows=[...tables[table]];
 const q={select(){return q;},eq(key,value){rows=rows.filter(row=>row[key]===value);return q;},is(key,value){rows=rows.filter(row=>row[key]===value);return q;},in(key,values){rows=rows.filter(row=>values.includes(row[key]));return q;},order(){return q;},limit(){return q;},not(key,operator,value){rows=rows.filter(row=>row[key]!==value);return q;},or(value){const day=value.match(/participation_date.eq.(\d{4}-\d{2}-\d{2})/)[1];rows=rows.filter(row=>row.participation_date===null||row.participation_date===day);return q;},async maybeSingle(){return rows.length>1?{data:null,error:true}:{data:rows[0]??null,error:null};},then(resolve,reject){return Promise.resolve({data:rows,error:null}).then(resolve,reject);}};
 return q;
}};
const data=load('src/lib/missions/data.ts',{'server-only':{},'@/lib/env':{getSupabasePublicConfig:()=>configured?{}:null},'@/lib/supabase/server':{createClient:async()=>db},'@/lib/mission-rounds':{...rounds,bangkokDay:()=>today}});
const available=await data.getAvailableMissions('self');
ok('list loads with multiple days present',available.status==='ready');
const daily=available.data.find(m=>m.id==='daily');
ok('list selects current day only',daily.participation.id==='today-round');
ok('list uses original round goal and price',daily.points===30&&daily.target_value===3000&&daily.requires_evidence);
ok('list separates pending from approved',daily.participation.pending_value===1500&&daily.participation.progress_value===0);
ok('legacy once-only participation remains visible',available.data.find(m=>m.id==='once').participation.id==='once-round');
const detail=await data.getMissionDetail('daily','self');
ok('detail defaults to current round',detail.status==='ready'&&detail.data.participation.id==='today-round'&&detail.data.roundDay===today);
ok('detail presents preserved round terms',detail.data.mission.participation_terms==='Original terms');
const historical=await data.getMissionDetail('daily','self',yesterday);
ok('historical detail selects exact previous day',historical.data.participation.id==='old-round'&&historical.data.roundDay===yesterday);
ok('historical detail keeps pending values',historical.data.participation.pending_value===3000);
ok('future round cannot be browsed',(await data.getMissionDetail('daily','self','2026-10-27')).data===null);
ok('invalid round date returns no detail',(await data.getMissionDetail('daily','self','2026-02-30')).data===null);
ok('once-only detail uses legacy null date',(await data.getMissionDetail('once','self')).data.participation.id==='once-round');
tables.activities=[{id:'historical-activity',user_mission_id:'old-round',user_id:'self',value:3000,unit:'steps',verification_status:'pending'}];
const history=await data.getHistoryData('self');
ok('history keeps snapshot mission titles',history.data.missions.find(m=>m.id==='old-round').missionTitle==='Original round title');
ok('activity history uses its round snapshot title',history.data.activities[0].missionTitle==='Original round title');
configured=false;
ok('missing environment handled as setup',(await data.getAvailableMissions('self')).status==='setup');
console.log(`Completed ${count} daily date/status/data selection checks with database doubles.`);
